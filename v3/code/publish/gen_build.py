"""Generate build_tables.sql (production targets) and build_tables_dryrun.sql (openalex.transient targets) for oxjob #1322.
  python3 gen_build.py [--wk openalex.transient.kw1322v3_work_keywords] [--vocab openalex.transient.kw1322v3_vocab] [--cutover 2026-09-28]
Source schemas: work_keywords(work_id 'W123', keyword_id 'keywords/<kid>', display_name, position INT, score DOUBLE 0-1);
vocab(keyword_id, kid, display_name, works_count, n_forms)."""
import argparse, os
ap = argparse.ArgumentParser()
ap.add_argument('--wk', default='openalex.transient.kw1322v3_work_keywords'); ap.add_argument('--vocab', default='openalex.transient.kw1322v3_vocab')
ap.add_argument('--cutover', default='2026-09-28', help='created_date for keywords with no legacy slug (the day keywords_v2 is first built)')
ap.add_argument('--tagger-version', default='kw1322-student-v3'); ap.add_argument('--vocab-version', default='kw1322-v3'); a = ap.parse_args()
HERE = os.path.dirname(os.path.abspath(__file__))

def wk_select(wk, vocab, where=''):
    return f"""SELECT
  CAST(SUBSTRING(k.work_id, 2) AS BIGINT) AS work_id,
  -- ARRAY<STRUCT<id STRING, display_name STRING, score FLOAT>> in position order: the exact type of openalex_works.keywords
  TRANSFORM(
    ARRAY_SORT(COLLECT_LIST(NAMED_STRUCT(
      'position', k.position,
      'id', CONCAT('https://openalex.org/', k.keyword_id),
      'display_name', v.display_name,
      'score', CAST(k.score AS FLOAT)))),
    x -> NAMED_STRUCT('id', x.id, 'display_name', x.display_name, 'score', x.score)
  ) AS keywords,
  '{a.tagger_version}' AS tagger_version,
  CURRENT_TIMESTAMP() AS updated_at
FROM {wk} k
JOIN {vocab} v ON v.keyword_id = k.keyword_id{where}
GROUP BY 1"""

def vocab_select(vocab):
    return f"""SELECT
  CONCAT('https://openalex.org/', v.keyword_id) AS id,
  v.kid,
  v.display_name,
  CAST(COALESCE(l.created, TIMESTAMP'{a.cutover} 00:00:00') AS TIMESTAMP) AS created_date,   -- legacy slug keeps its date
  '{a.vocab_version}' AS vocab_version
FROM {vocab} v
LEFT JOIN (SELECT keyword_id AS kid, MIN(created_datetime) AS created FROM openalex.common.keywords GROUP BY 1) l ON l.kid = v.kid"""

CHECKS = lambda t_wk, t_v: f"""
-- Checks (SELECT only)
SELECT COUNT(*) AS works, SUM(SIZE(keywords)) AS rows, MIN(SIZE(keywords)) AS min_kw, MAX(SIZE(keywords)) AS max_kw,
       COUNT_IF(EXISTS(keywords, x -> x.display_name IS NULL OR x.score IS NULL)) AS works_with_nulls
FROM {t_wk};
SELECT COUNT(*) AS works, COUNT(DISTINCT work_id) AS distinct_works FROM {t_wk};           -- must be equal
SELECT (SELECT typeof(keywords) FROM {t_wk} LIMIT 1) AS v2_type,
       (SELECT typeof(keywords) FROM openalex.works.openalex_works LIMIT 1) AS works_type;   -- must be equal
SELECT COUNT(*) AS n, COUNT(DISTINCT id) AS ids, COUNT_IF(created_date < TIMESTAMP'{a.cutover}') AS legacy_dated,
       COUNT_IF(id NOT RLIKE '^https://openalex\\\\.org/keywords/.+$') AS bad_ids FROM {t_v};
-- works in openalex_works with >= 1 keyword (smoke test 13 thresholds 50% all / 65% non-xpac)
SELECT COUNT(*) AS works, COUNT_IF(wk.work_id IS NOT NULL) AS with_kw, COUNT_IF(NOT COALESCE(w.is_xpac, false)) AS nonx,
       COUNT_IF(wk.work_id IS NOT NULL AND NOT COALESCE(w.is_xpac, false)) AS nonx_with_kw
FROM openalex.works.openalex_works w LEFT JOIN {t_wk} wk ON wk.work_id = w.id;
"""

for name, t_wk, t_v, note in [
    ('build_tables.sql', 'openalex.works.work_keywords_v2', 'openalex.common.keywords_v2',
     "PRODUCTION WRITES: needs Jason's yes, backups.sql first, charter write-log lines before and after."),
    ('build_tables_dryrun.sql', 'openalex.transient.kw1322v3_dryrun_work_keywords_v2', 'openalex.transient.kw1322v3_dryrun_keywords_v2',
     'Dry run: writes ONLY openalex.transient; safe to run.')]:
    open(f'{HERE}/{name}', 'w').write(f"""-- GENERATED by gen_build.py (oxjob #1322). {note}
-- Sources: {a.wk} / {a.vocab}; tagger_version {a.tagger_version}; vocab_version {a.vocab_version}; new-keyword created_date {a.cutover}.

-- § 2a: served per-work keywords (read by CreateWorksEnriched c9)
CREATE OR REPLACE TABLE {t_wk}
COMMENT 'oxjob #1322: served work keywords (student tagger). Replaces work_concepts.keywords. New works are appended nightly (INSERT of new work_ids only).'
AS {wk_select(a.wk, a.vocab)};

-- § 2b: keyword vocabulary (read by CreateKeywordsAPI c1)
CREATE OR REPLACE TABLE {t_v}
COMMENT 'oxjob #1322: keyword vocabulary for the /keywords entity. created_date inherited from legacy openalex.common.keywords where the slug existed.'
AS {vocab_select(a.vocab)};
{CHECKS(t_wk, t_v)}""")
print('wrote build_tables.sql, build_tables_dryrun.sql')
